
import React from "react";
import {
  Users,
  BookOpen,
  IndianRupee,
  GraduationCap,
  TrendingUp,
  Clock,
  Eye,
} from "lucide-react";

import {
  ResponsiveContainer,
  BarChart,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
} from "recharts";



import {
  Card,
  CardContent,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { useGetCreatorCourseQuery } from "@/features/api/courseapi";

const formatCurrency = (amount) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount || 0);

const InstructorDashboard = () => {
  const { data, isLoading, isError } = useGetCreatorCourseQuery();

  if (isLoading) {
    return (
      <div className="p-6 text-center">
        Loading dashboard...
      </div>
    );
  }

  if (isError) {
    return (
      <div className="p-6 text-center text-red-500">
        Failed to load dashboard data.
      </div>
    );
  }

  const courses = data?.courses || [];

  // Separate published and unpublished courses
  const publishedCourses = courses.filter(
    (course) => course.isPublished
  );

  const draftCourses = courses.filter(
    (course) => !course.isPublished
  );

  // Calculate course statistics
  const totalStudents = publishedCourses.reduce(
    (total, course) =>
      total + (course.enrolledStudents?.length || 0),
    0
  );

  const totalRevenue = publishedCourses.reduce(
    (total, course) =>
      total +
      (course.coursePrice || 0) *
        (course.enrolledStudents?.length || 0),
    0
  );

  const totalCourses = courses.length;

  // Revenue comparison chart
  const chartData = publishedCourses.map((course) => ({
    name: course.courseTitle,
    revenue:
      (course.coursePrice || 0) *
      (course.enrolledStudents?.length || 0),
  }));

  const stats = [
    {
      title: "Total Revenue",
      value: formatCurrency(totalRevenue),
      icon: IndianRupee,
      description: "Estimated gross course revenue",
    },
    {
      title: "Total Enrollments",
      value: totalStudents,
      icon: Users,
      description: "Across published courses",
    },
    {
      title: "Published Courses",
      value: publishedCourses.length,
      icon: GraduationCap,
      description: "Currently available courses",
    },
    {
      title: "Draft Courses",
      value: draftCourses.length,
      icon: Clock,
      description: "Waiting to be published",
    },
  ];

  return (
    <div className="min-h-screen bg-background p-4 md:p-8 space-y-8">

      {/* Header */}
      <div>
        <h1 className="text-2xl md:text-3xl font-bold">
          Instructor Dashboard
        </h1>
        <p className="text-muted-foreground mt-2">
          Track your courses, enrollments and revenue.
        </p>
      </div>

      {/* Statistics Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-4 gap-4">

        {stats.map((stat, index) => {
          const Icon = stat.icon;

          return (
            <Card key={index}>
              <CardContent className="p-5">
                <div className="flex justify-between items-start">
                  <div>
                    <p className="text-sm text-muted-foreground">
                      {stat.title}
                    </p>

                    <h2 className="text-2xl font-bold mt-2">
                      {stat.value}
                    </h2>

                    <p className="text-xs text-muted-foreground mt-2">
                      {stat.description}
                    </p>
                  </div>

                  <div className="p-3 rounded-lg bg-primary/10">
                    <Icon className="w-5 h-5 text-primary" />
                  </div>
                </div>
              </CardContent>
            </Card>
          );
        })}

      </div>

      {/* Revenue Chart */}
      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <TrendingUp className="w-5 h-5" />
            Course Revenue Comparison
          </CardTitle>
          <p className="text-sm text-muted-foreground">
            Estimated revenue generated by each published course.
          </p>
        </CardHeader>

        <CardContent>
          {chartData.length > 0 ? (
            <div className="w-full h-[350px]">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart
                  data={chartData}
                  margin={{
                    top: 10,
                    right: 20,
                    left: 10,
                    bottom: 10,
                  }}
                >
                  <CartesianGrid
                    strokeDasharray="3 3"
                    vertical={false}
                    stroke="hsl(var(--border))"
                  />

                  <XAxis
                    dataKey="name"
                    tick={{ fontSize: 11 }}
                    interval={0}
                    angle={-15}
                    textAnchor="end"
                    height={75}
                  />

                  <YAxis
                    tickFormatter={(value) =>
                      `₹${value / 1000}k`
                    }
                  />

                  <Tooltip
                    formatter={(value) => [
                      formatCurrency(value),
                      "Revenue",
                    ]}
                    contentStyle={{
                      borderRadius: "10px",
                      border: "1px solid hsl(var(--border))",
                      backgroundColor: "hsl(var(--card))",
                    }}
                  />

                  <Bar
                    dataKey="revenue"
                    fill="#16a34a"
                    radius={[6, 6, 0, 0]}
                  />
                </BarChart>
              </ResponsiveContainer>
            </div>
          ) : (
            <p className="text-center text-muted-foreground py-16">
              No published courses available for comparison.
            </p>
          )}
        </CardContent>
      </Card>

      {/* Published Courses */}
      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <BookOpen className="w-5 h-5" />
            Published Courses
          </CardTitle>
        </CardHeader>

        <CardContent>
          {publishedCourses.length > 0 ? (
            <div className="overflow-x-auto">
              <table className="w-full text-sm text-left">
                <thead>
                  <tr className="border-b text-muted-foreground">
                    <th className="p-3">Course</th>
                    <th className="p-3">Price</th>
                    <th className="p-3">Students</th>
                    <th className="p-3">Total Revenue</th>
                  </tr>
                </thead>

                <tbody>
                  {publishedCourses.map((course) => {
                    const students =
                      course.enrolledStudents?.length || 0;

                    const revenue =
                      (course.coursePrice || 0) * students;

                    return (
                      <tr
                        key={course._id}
                        className="border-b hover:bg-muted/50 transition-colors"
                      >
                        <td className="p-3 min-w-[200px]">
                          <div className="flex items-center gap-3">
                            <img
                              src={course.courseThumbnail}
                              alt={course.courseTitle}
                              className="w-12 h-10 object-cover rounded-md"
                            />

                            <div>
                              <p className="font-medium">
                                {course.courseTitle}
                              </p>
                              <p className="text-xs text-muted-foreground">
                                {course.category}
                              </p>
                            </div>
                          </div>
                        </td>

                        <td className="p-3">
                          {formatCurrency(course.coursePrice)}
                        </td>

                        <td className="p-3">
                          <span className="flex items-center gap-2">
                            <Users className="w-4 h-4 text-muted-foreground" />
                            {students}
                          </span>
                        </td>

                        <td className="p-3 font-semibold text-green-600">
                          {formatCurrency(revenue)}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          ) : (
            <p className="text-center text-muted-foreground py-10">
              You haven't published any courses yet.
            </p>
          )}
        </CardContent>
      </Card>

      {/* Unpublished Courses */}
      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <Clock className="w-5 h-5" />
            Unpublished Courses
            <span className="text-sm text-muted-foreground">
              ({draftCourses.length})
            </span>
          </CardTitle>

          <p className="text-sm text-muted-foreground">
            These courses are not publicly available yet.
          </p>
        </CardHeader>

        <CardContent>
          {draftCourses.length > 0 ? (
            <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-4">
              {draftCourses.map((course) => (
                <div
                  key={course._id}
                  className="border rounded-xl overflow-hidden"
                >
                  <img
                    src={course.courseThumbnail}
                    alt={course.courseTitle}
                    className="w-full h-40 object-cover"
                  />

                  <div className="p-4 space-y-3">
                    <div className="flex justify-between items-center gap-2">
                      <span className="text-xs px-2 py-1 rounded-full bg-yellow-500/10 text-yellow-600">
                        Draft
                      </span>

                      <span className="text-xs text-muted-foreground">
                        {course.category}
                      </span>
                    </div>

                    <h3 className="font-semibold">
                      {course.courseTitle}
                    </h3>

                    <p className="text-sm text-muted-foreground">
                      {course.courseSubTitle}
                    </p>

                    <div className="flex justify-between items-center text-sm">
                      <span>
                        {course.lectures?.length || 0} Lectures
                      </span>

                      <span className="font-medium">
                        {formatCurrency(course.coursePrice)}
                      </span>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          ) : (
            <p className="text-center text-muted-foreground py-10">
              No unpublished courses.
            </p>
          )}
        </CardContent>
      </Card>

      {/* Final Total Revenue */}
      <Card className="border-green-600/30 bg-green-600/5">
        <CardContent className="p-6">
          <div className="flex flex-col sm:flex-row justify-between items-center gap-4">
            <div>
              <h2 className="text-lg font-semibold">
                Total Estimated Sales
              </h2>
              <p className="text-sm text-muted-foreground">
                Across all published courses
              </p>
            </div>

            <h1 className="text-3xl md:text-4xl font-bold text-green-600">
              {formatCurrency(totalRevenue)}
            </h1>
          </div>
        </CardContent>
      </Card>

    </div>
  );
};

export default InstructorDashboard;
